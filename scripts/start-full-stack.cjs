const { spawn, spawnSync } = require('node:child_process');
const { writeFileSync } = require('node:fs');
const net = require('node:net');

const pnpm = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm';

function run(command, args, env) {
  const result = spawnSync(command, args, {
    cwd: process.cwd(),
    env,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    process.exit(result.status || 1);
  }
}

function isPortFree(port) {
  return new Promise((resolve) => {
    const server = net.createServer();
    server.once('error', () => resolve(false));
    server.once('listening', () => server.close(() => resolve(true)));
    server.listen(port, '127.0.0.1');
  });
}

function runningPostgresPort() {
  const result = spawnSync('docker', [
    'port', 'futureflow-postgres', '5432/tcp',
  ], { encoding: 'utf8' });
  if (result.status !== 0) return '';

  // Docker may return IPv4 and IPv6 bindings. Reuse the first published host
  // port so a second `pnpm start` never recreates the existing database on a
  // different port.
  const match = result.stdout.match(/:(\d+)\s*(?:\r?\n|$)/);
  return match?.[1] || '';
}

async function choosePostgresPort() {
  if (process.env.POSTGRES_PORT) return process.env.POSTGRES_PORT;
  const existingPort = runningPostgresPort();
  if (existingPort) return existingPort;
  if (await isPortFree(5432)) return '5432';
  for (let port = 5433; port <= 5450; port += 1) {
    if (await isPortFree(port)) return String(port);
  }
  throw new Error('No free local PostgreSQL port found between 5432 and 5450. Set POSTGRES_PORT explicitly.');
}

function persistRuntimePostgresPort(port) {
  // Keep command-line migrations and later gateway restarts aligned with the
  // port selected by this starter, without rewriting user-managed .env.
  writeFileSync(
    '.futureflow.runtime.env',
    `# Generated by pnpm start. Do not commit.\nPOSTGRES_PORT=${port}\n`,
    { mode: 0o600 },
  );
}

function health(name) {
  const result = spawnSync('docker', [
    'inspect', '--format', '{{.State.Health.Status}}', name,
  ], { encoding: 'utf8' });
  return result.status === 0 ? result.stdout.trim() : 'unknown';
}

async function waitForHealth(name, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (health(name) === 'healthy') return;
    await new Promise((resolve) => setTimeout(resolve, 2000));
  }
  throw new Error(`${name} did not become healthy in time. Inspect it with: docker compose logs ${name.replace('futureflow-', '')}`);
}

async function main() {
  const infrastructureOnly = process.argv.includes('--infrastructure-only');
  const postgresPort = await choosePostgresPort();
  persistRuntimePostgresPort(postgresPort);
  const env = { ...process.env, POSTGRES_PORT: postgresPort };
  if (!process.env.POSTGRES_PORT && postgresPort !== '5432') {
    console.log(`Host port 5432 is already in use; futureFlow PostgreSQL will use ${postgresPort}.`);
  }

  console.log('Starting the full futureFlow stack: PostgreSQL, Dify API/Worker/Web, Redis, Weaviate, gateway, and canvas.');
  run('docker', ['compose', 'up', '-d'], env);
  await waitForHealth('futureflow-postgres', 90_000);
  await waitForHealth('futureflow-dify-api', 150_000);
  run(pnpm, ['--filter', 'futureflow-gateway', 'migration:run'], env);
  if (infrastructureOnly) {
    console.log('The full container stack is ready and futureFlow database migrations have completed.');
    return;
  }

  const child = spawn(pnpm, ['run', 'dev:concurrent'], {
    cwd: process.cwd(),
    env,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  const stop = (signal) => child.kill(signal);
  process.on('SIGINT', () => stop('SIGINT'));
  process.on('SIGTERM', () => stop('SIGTERM'));
  child.on('error', (error) => {
    console.error(`Failed to start futureFlow application services: ${error.message}`);
    process.exit(1);
  });
  child.on('exit', (code) => process.exit(code || 0));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
